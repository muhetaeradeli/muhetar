#!/usr/bin/env python3
"""Copy the film's photographs into assets/ (long side 2880 px, JPEG) and write assets/credits.js.
   python3 tools/import_photos.py <folder with downloaded originals named <name>.jpg>
Every photo is from Wikimedia Commons under the licence listed here; the end card credits the authors.
A photo that is not in the folder is left out, and the film paints that shot instead."""
import json, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PHOTOS = [  # name, Commons file, author, licence
    ('steppe_horses', 'Kazakhstan steppe Almaty Province (1) horses.jpg', 'Radosław Botev', 'CC BY 3.0 PL'),
    ('horses_wide', 'Horses Grazing on the Kazakhstani Steppe (7131707195).jpg', 'Ken and Nyetta', 'CC BY 2.0'),
    ('steppes', 'Steppes of Kazakhstan.jpg', 'Togzhan Ibrayeva', 'CC BY-SA 4.0'),
    ('sunset_south', 'Sunset on the South Kazakhstani steppe.jpg', 'Андрей Касаткин', 'CC BY 2.0'),
    ('kazakh_yurt', 'Kazakh yurt.jpg', 'Ludovic Hirlimann', 'CC BY-SA 2.0'),
    ('shanyrak_kz', 'Казахский шанарак.jpg', 'Alexandr Frolov', 'CC BY-SA 4.0'),
    ('syrmak', 'Kazakh syrmak.jpg', 'Arnur Sarybai', 'CC0'),
    ('korgal', 'Korgalzhinskiy Nature Reserve.JPG', 'Tomiris', 'CC BY-SA 3.0'),
    ('sunset_steppe2', 'Sunset over the Steppe (4983155596).jpg', 'upyernoz', 'CC BY 2.0'),
    ('yurt_cliffs', 'Yurt at the Foot of the Cliffs, Aktobe Region, Kazakhstan.jpg', 'Danatleg122', 'CC BY 4.0'),
    ('shangrak', 'Shangrak.JPG', 'Man77', 'CC BY 3.0'),
    ('jewelry', 'Kazakh jewelry.jpg', 'Akbota Bakyt', 'CC BY-SA 4.0'),
    ('naurzum', 'Naurzum nature reserve.JPG', 'Tomiris', 'CC BY-SA 3.0'),
    ('konaev1', 'Конаевский округ, лошади (1).jpg', 'Nikolai Bulykin', 'CC BY-SA 4.0'),
    ('yurt_homes', 'Traditional Kazakh Mobile Homes (7508095304).jpg', 'Ken and Nyetta', 'CC BY 2.0'),
    ('applique', 'Applique de vêtement kazakh (musée Guimet) (5361665450).jpg', 'Jean-Pierre Dalbéra', 'CC BY 2.0'),
    ('cold_steppe', 'Cold Steppe (4983154024).jpg', 'upyernoz', 'CC BY 2.0'),
]
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'assets')
os.makedirs(os.path.join(ROOT, 'assets'), exist_ok=True)
credits = []
for name, file, author, lic in PHOTOS:
    a, b = os.path.join(src, name + '.jpg'), os.path.join(ROOT, 'assets', name + '.jpg')
    if not os.path.exists(a) or os.path.getsize(a) < 1000: continue
    if os.path.abspath(a) != os.path.abspath(b):
        subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-i', a, '-vf', "scale='if(gt(iw,ih),min(2880,iw),-2)':'if(gt(iw,ih),-2,min(2880,ih))'", '-q:v', '3', b])
    credits.append({'name': name, 'file': file, 'author': author, 'license': lic,
                    'url': 'https://commons.wikimedia.org/wiki/File:' + file.replace(' ', '_')})
open(os.path.join(ROOT, 'assets', 'credits.js'), 'w').write(
    '// generated by tools/import_photos.py: the photographs in assets/ and their authors (Wikimedia Commons)\n'
    '(function () { const CREDITS = ' + json.dumps(credits, ensure_ascii=False, indent=1) +
    "; if (typeof module !== 'undefined') module.exports = CREDITS; else globalThis.CREDITS = CREDITS; })();\n")
print(f'{len(credits)} photos in assets/')
