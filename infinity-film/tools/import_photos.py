#!/usr/bin/env python3
"""Copy the film's photographs into assets/ and write assets/credits.js.
   python3 tools/import_photos.py <folder>
The folder holds <name>.jpg files and a meta.json {name: {title, creator, license, page}} (as written by the
download step). The photos in it are expected to be upscaled already (Real-ESRGAN, tools/upscale.py), so they
stay sharp on a big screen; here they are only fitted to at most 2880 px wide. Every Flickr photo used is
credited on the end card (a photo whose licence is '—' was supplied with the text and is not listed).
A photo that is missing is left out, and the film paints that shot instead."""
import json, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# the photographs the film uses, in order of appearance
CHOSEN = [  # every photograph the film shows (film-plan.js)
    'a_ast1', 'a_ast2', 'a_ast5', 'ak_sunset', 'az_sunset', 'c_costume', 'c_inger', 'c_pattern', 'ch_int1',
    'ch_int2', 'ch_int3', 'dal_objets', 'dal_vase', 'gv_yurt', 'ir_yurt', 'live_stars', 'my_1', 'my_2', 'n_camels',
    'n_felt', 'n_gerdoor', 'n_horseman', 'n_museumtash', 'n_sheep1', 'n_sheep2', 'n_sheep3', 'n_silk',
    'n_tamgaly1', 'n_tamgaly2', 'n_timeless', 'n_wedding', 'n_winter', 'n_wood', 'nin_pano', 'p_children',
    'p_chris', 'p_eagle', 'p_eagle2', 'p_family', 'p_grandma', 'p_nomadfam', 'p_spin', 'p_xjfamily', 's_alatau1',
    's_alatau3', 's_apricot', 's_before', 's_eagle', 's_sunrise', 's_sunrise2', 's_talas', 'u_lobby', 'u_museum',
    'u_pch1', 'u_tyl4', 'undp_altyn', 'undp_crane', 'undp_saiga', 'up_silky', 'up_yurts', 'user_shanyrak',
    'y_frame2',
    # the second search: felt, yurt interiors, shanyrak and uyks, pastures, eagle hunters, night sky
    'n2_shyrdak', 'n2_shyrdak2', 'n2_yint1', 'n2_yint2', 'n2_yint3', 'n2_uyk', 'n2_yint4', 'n2_eagle', 'n2_eagle2', 'n2_horsesdrink', 'n2_herd', 'n2_jailau', 'n2_jailau2', 'n2_argali', 'n2_feltcarry', 'n2_winterchild', 'n2_camelsnow', 'n2_horse', 'n2_dombra', 'n2_milky', 'n2_dusk', 'n2_mist', 'n2_charyn', 'n2_hunters', 'n2_yurtdesert', 'n2_rugwoman', 'n2_yurtmtn', 'n2_yurtmtn2', 'n2_build', 'n2_shanband', 'n2_yurtband', 'n2_uykred', 'n2_shanlight', 'n2_tulip', 'n2_tulip2', 'n2_textile', 'n2_yurtforest', 'y_ceilnight', 'y_frame', 'dal_applique', 'hicks_horses', 'n_winter2',
    # the third search (Wikimedia Commons): Kazakh museum objects with their region, a real шежіре, a Kazakh autumn
    'k_syrmak', 'k_jurtmus', 'k_shapanA', 'k_shapanK', 'k_door', 'k_doorfrag', 'k_felt', 'k_feltrug', 'k_kebeje', 'k_sandyk', 'k_tanba', 'k_grif', 'k_ger', 'k_carpet', 'k_nauryz', 'k_ubran', 'k_shanyrak', 'k_orn', 'k_belt', 'k_shezhire', 'k_autumn',
]
src = sys.argv[1]                                   # the originals and their meta.json
up = sys.argv[2] if len(sys.argv) > 2 else src       # the upscaled versions (tools/upscale.py), used when present
meta = json.load(open(os.path.join(src, 'meta.json')))
meta.setdefault('user_shanyrak', {'title': 'Шаңырақ', 'creator': '—', 'license': '—', 'page': ''})  # supplied with the text
os.makedirs(os.path.join(ROOT, 'assets'), exist_ok=True)
credits = []
for name in CHOSEN:
    a, b = os.path.join(up, name + '.jpg'), os.path.join(ROOT, 'assets', name + '.jpg')
    if not os.path.exists(a): a = os.path.join(src, name + '.jpg')
    if not os.path.exists(a) or name not in meta: print('missing', name); continue
    subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-i', a, '-vf', "scale='min(2880,iw)':-2:flags=lanczos", '-q:v', '2', b])
    m = meta[name]
    lic = '—' if m['license'] == '—' else m['license'].strip().upper().replace('CC0', 'CC0 ').replace('BY', 'CC BY', 1) if not m['license'].lower().startswith('cc0') else 'CC0'
    credits.append({'name': name, 'title': m['title'] or '(untitled)', 'author': m['creator'], 'license': lic.replace('  ', ' ').strip(), 'url': m['page']})
open(os.path.join(ROOT, 'assets', 'credits.js'), 'w').write(
    '// generated by tools/import_photos.py: the photographs in assets/ and their authors (via Flickr / Openverse and Wikimedia Commons)\n'
    '(function () { const CREDITS = ' + json.dumps(credits, ensure_ascii=False, indent=1) +
    "; if (typeof module !== 'undefined') module.exports = CREDITS; else globalThis.CREDITS = CREDITS; })();\n")
print(f'{len(credits)} photos in assets/')
for c in credits: print(f"  {c['name']:12} {c['license']:16} {c['author']}")
